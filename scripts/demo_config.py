"""One literal, project-local configuration for the Hotel A demo (stdlib only)."""
import os
from pathlib import Path
import re
import secrets
import stat


ROOT = Path(__file__).resolve().parents[1]
HOST = '127.0.0.1'
NATIVE_PORT = '55488'
DOCKER_PORT = '55487'
API_BIND = f'{HOST}:8017'
UI_PORT = '5187'
UI_ORIGIN = f'http://{HOST}:{UI_PORT}'

# Tool discovery, home, temporary directories and locale; no libpq service/hostaddr,
# Python/Node options, VITE_* variables, proxy settings or deployment credentials.
_SYSTEM_KEYS = set('''PATH PATHEXT SYSTEMROOT SYSTEMDRIVE WINDIR COMSPEC TEMP TMP TMPDIR HOME
    USER LOGNAME USERNAME HOMEDRIVE HOMEPATH USERPROFILE APPDATA LOCALAPPDATA PROGRAMDATA
    PROGRAMFILES PROGRAMFILES(X86) PROGRAMW6432 XDG_CONFIG_HOME XDG_RUNTIME_DIR LANG LC_ALL
    LC_CTYPE TERM'''.split())


def system_env(inherited):
    return {k: v for k, v in inherited.items() if k.upper() in _SYSTEM_KEYS}


def _read_values(path, allowed):
    # Only the KEY=literal format generated by the helpers. Don't interpret shell
    # expressions, "export", duplicate keys or dotenv interpolation differently from Django.
    try:
        mode = path.lstat().st_mode
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(mode):
        raise SystemExit('The demo .env must be a regular file in the checkout.')
    try:
        text = path.read_text(encoding='utf-8')
    except UnicodeError:
        raise SystemExit('The demo .env must be UTF-8.') from None
    values = {}
    for n, line in enumerate(text.split('\n'), 1):  # read_text already normalizes CR/LF
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        key, sep, value = line.partition('=')
        if not sep or key not in allowed or key in values:
            raise SystemExit(f'Unexpected or repeated setting on demo .env line {n}.')
        values[key] = value
    return values


def prepare(root, port, inherited):
    """Validate file AND invoking environment before creating anything. Never repair an existing file."""
    if port not in (NATIVE_PORT, DOCKER_PORT):
        raise ValueError('Unknown demo database port.')
    fixed = {
        'POSTGRES_HOST': HOST, 'POSTGRES_PORT': port, 'POSTGRES_DB': 'hotel_a', 'POSTGRES_USER': 'hotel_a',
        'HMS_ENV': 'local', 'HMS_DEBUG': '1', 'HMS_SECURE_COOKIES': '0',
        'HMS_ALLOWED_HOSTS': 'localhost,127.0.0.1',
        'HMS_CSRF_TRUSTED_ORIGINS': f'{UI_ORIGIN},http://localhost:{UI_PORT}', 'HMS_PUBLIC_URL': UI_ORIGIN,
        'HMS_API_TARGET': f'http://{API_BIND}', 'HMS_TRUST_PROXY': '0', 'HMS_HTTPS': '0', 'HMS_NUM_PROXIES': '0',
        'HMS_EMAIL_HOST': '', 'HMS_EMAIL_PORT': '587', 'HMS_EMAIL_USER': '', 'HMS_EMAIL_PASSWORD': '',
        'HMS_EMAIL_FROM': '', 'HMS_EMAIL_TLS': '1', 'HMS_MEDIA_ROOT': str(root / 'backend' / 'media'),
        'DJANGO_SETTINGS_MODULE': 'config.settings',
    }
    secret_keys = {'HMS_SECRET_KEY', 'POSTGRES_PASSWORD'}
    path = root / '.env'
    values = _read_values(path, fixed.keys() | secret_keys)
    if values is None:
        credentials = {'HMS_SECRET_KEY': secrets.token_urlsafe(50), 'POSTGRES_PASSWORD': secrets.token_urlsafe(32)}
    else:
        required = secret_keys | {'HMS_DEBUG', 'POSTGRES_HOST', 'POSTGRES_PORT', 'POSTGRES_DB', 'POSTGRES_USER'}
        missing = sorted(required - values.keys())
        if missing:
            raise SystemExit(f'The local demo .env is missing {", ".join(missing)}.')
        for key in values.keys() & fixed.keys():
            if values[key] != fixed[key]:
                raise SystemExit(f'{key} in .env does not match this local demo. Existing file preserved.')
        # Compatible with secrets from both original launchers. A literal alphabet
        # keeps credentials identical even for other tools reading .env with python-dotenv.
        credentials = {key: values[key] for key in secret_keys}
        for key, value in credentials.items():
            if not re.fullmatch(r'[A-Za-z0-9_-]{32,}', value):
                raise SystemExit(f'{key} in the demo .env must be a long (32+), URL-safe literal.')

    settings = {**fixed, **credentials}
    for key, value in inherited.items():
        name = key.upper()  # Windows environment names are case-insensitive.
        if name.startswith(('POSTGRES_', 'HMS_')) or name == 'DJANGO_SETTINGS_MODULE':
            if name not in settings or settings[name] != value:
                # Identify the setting, never its value (even on a password mismatch).
                raise SystemExit(f'Conflicting inherited {name}; unset it before launching the local demo.')

    if values is None:
        # Absolute media path and Django module are pinned at launch, not persisted.
        text = '# Private synthetic Hotel A demo settings.\n' + ''.join(
            f'{k}={v}\n' for k, v in settings.items() if k not in ('HMS_MEDIA_ROOT', 'DJANGO_SETTINGS_MODULE'))
        try:
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:
            raise SystemExit('The demo .env appeared during setup; re-run to validate it.') from None
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            stream.write(text)
    return settings
