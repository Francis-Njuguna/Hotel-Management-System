import { fireEvent, screen, within } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import { RoomsPage } from '../RoomsPage';
import { openPage, pageOf, room } from './harness';

describe('Room catalog', () => {
  it('rejects an unsafe photo locally and submits a safe multipart envelope with the exact decimal and facilities', async () => {
    const calls = openPage(<RoomsPage />, ({ method }) => method === 'GET' ? { data: pageOf([]) } : { data: room, status: 201 });
    fireEvent.click(await screen.findByRole('button', { name: 'Add room' }));
    const dialog = within(screen.getByRole('dialog', { name: 'Add room' }));
    fireEvent.change(dialog.getByLabelText(/Room number/), { target: { value: room.number } });
    fireEvent.change(dialog.getByLabelText('Nightly rate (KES)'), { target: { value: '9999999999.90' } });
    fireEvent.change(dialog.getByLabelText(/Facilities/), { target: { value: 'Desk\nWi-Fi\n\n' } });
    const input = dialog.getByLabelText('Room photo');
    fireEvent.change(input, { target: { files: [new File(['test'], 'test.svg', { type: 'image/svg+xml' })] } });
    fireEvent.click(dialog.getByRole('button', { name: 'Create room' }));
    expect(dialog.getByRole('alert')).toHaveTextContent(/JPEG or PNG/);
    expect(calls.filter(c => c.method === 'POST')).toHaveLength(0);
    fireEvent.change(input, { target: { files: [new File(['synthetic test bytes'], 'fixture.png', { type: 'image/png' })] } });
    fireEvent.click(dialog.getByRole('button', { name: 'Create room' }));
    expect(await screen.findByText(/Room T04 created/)).toBeVisible();
    const post = calls.find(c => c.method === 'POST');
    expect(post?.path).toBe('rooms/');
    expect(post?.body).toBeInstanceOf(FormData);
    const form = post?.body as FormData;
    expect(form.get('nightly_rate')).toBe('9999999999.90');
    expect(form.get('facilities')).toBe('["Desk","Wi-Fi"]');
    expect(form.get('image')).toBeInstanceOf(File);
    expect(form.has('cleanliness')).toBe(false);
    expect(post?.headers.has('Content-Type')).toBe(false); // Boundary must be generated by the browser.
  });

  it('uses a dated, filtered availability request independently of the current room condition', async () => {
    const calls = openPage(<RoomsPage />, ({ path }) => ({ data: pageOf(path === 'rooms/availability/' ? [{ ...room, cleanliness: 'dirty', occupied: true }] : []) }), ['rooms.view']);
    expect(await screen.findByText(/No rooms match/)).toBeVisible();
    expect(screen.queryByRole('button', { name: 'Add room' })).not.toBeInTheDocument();
    fireEvent.change(screen.getByLabelText('Arrival date'), { target: { value: '2029-03-12' } });
    fireEvent.change(screen.getByLabelText('Departure date'), { target: { value: '2029-03-12' } });
    fireEvent.click(screen.getByRole('button', { name: 'Check availability' }));
    expect(screen.getByRole('alert')).toHaveTextContent('Departure must be later than arrival.');
    expect(calls.some(c => c.path === 'rooms/availability/')).toBe(false);
    fireEvent.change(screen.getByLabelText('Departure date'), { target: { value: '2029-03-14' } });
    fireEvent.change(screen.getByLabelText('Category'), { target: { value: 'Twin' } });
    fireEvent.click(screen.getByRole('button', { name: 'Check availability' }));
    const card = within(await screen.findByRole('article', { name: 'Room T04' }));
    expect(card.getByText('Occupied now')).toBeVisible();
    expect(card.getByText('Needs cleaning')).toBeVisible();
    expect(card.getByText('KES 2,450.50')).toBeVisible();
    const search = calls.find(c => c.path === 'rooms/availability/');
    expect(Object.fromEntries(search!.params)).toMatchObject({ arrival: '2029-03-12', departure: '2029-03-14', category: 'Twin', page: '1' });
  });

  it('patches changed catalog fields without overwriting the private photo or readiness', async () => {
    const calls = openPage(<RoomsPage />, ({ method }) => ({ data: method === 'PATCH' ? room : pageOf([{ ...room, image: '/api/v1/media/test-room.jpg' }]) }));
    fireEvent.click(await screen.findByRole('button', { name: 'Edit room T04' }));
    const dialog = within(screen.getByRole('dialog', { name: 'Edit room T04' }));
    fireEvent.change(dialog.getByLabelText('Nightly rate (KES)'), { target: { value: '1500.6' } });
    fireEvent.click(dialog.getByRole('button', { name: 'Save room changes' }));
    expect(await screen.findByText(/Room T04 updated/)).toBeVisible();
    expect(calls.find(c => c.method === 'PATCH')).toMatchObject({ path: 'rooms/4/', body: { nightly_rate: '1500.60' } });
    expect(Object.keys(calls.find(c => c.method === 'PATCH')!.body as object)).toEqual(['nightly_rate']);
  });
});
